with open(SCENE_PATH, encoding='utf-8') as f:
    data = json.load(f)
scenes = data['scenes']

# 清除旧的 year 字段
for v in scenes.values():
    v.pop('year', None)

marked = 0
counts = Counter()
for key, v in scenes.items():
    seg = v.get('segment', '')
    if seg in SEGMENT_YEARS:
        v['year'] = SEGMENT_YEARS[seg]
        marked += 1
        counts[seg] += 1

